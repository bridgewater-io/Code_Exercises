#include <iostream>

int main() {
  
  // First initials block
  std::cout << "  S S S  \n";
  std::cout << "S       S\n";
  std::cout << "S        \n";
  std::cout << "  S S S  \n";
  std::cout << "        S\n";
  std::cout << "S       S\n";
  std::cout << "  S S S  \n";

  // Second initials block
  std::cout << "B B B B  \n";
  std::cout << "B       B\n";
  std::cout << "B       B\n";
  std::cout << "B B B B  \n";
  std::cout << "B       B\n";
  std::cout << "B       B\n";
  std::cout << "B B B B  \n";

}
